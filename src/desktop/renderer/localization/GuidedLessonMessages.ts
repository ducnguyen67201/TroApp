/** Guided-lesson presentation copy follows the existing desktop locale selection. */
export function readGuidedLessonMessages(locale: DesktopLocale): {
  translateGuidedLesson: (text: string) => string;
} {
  return {
    translateGuidedLesson(text: string): string {
      return locale === DesktopLocale.VIETNAMESE ? (vietnamese[text] ?? text) : text;
    },
  };
}
